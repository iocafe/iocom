# Size excludes signal state byte.
osal_typeinfo = {
    "undef" : 0,
    "boolean" : 1,
    "char" : 1,
    "uchar" : 1,
    "short" : 2,
    "ushort" : 2,
    "int" : 4,
    "uint" : 4,
    "int64" : 8,
    "long" : 8,
    "float" : 4,
    "double" : 8,
    "dec01" : 2,
    "dec001" : 2,
    "str" : 1,
    "object" : 0,
    "pointer" : 0}

def check_valid_name(label, name, sz, allow_numbers):
    if name == None:
        all_failed(label + " name is not defined.")

    if len(name) >= sz:
        all_failed(label + " name '" + name + "' is too long. Maximum is " + str(sz - 1) + "characters.")

    if allow_numbers:
        if not re.match(r'^[A-Za-z0-9_]+$', name):
            all_failed(label + " name '" + name + "' may contain only characters 'A' - 'Z', 'a' - 'z', '0' -'9' and underscore '_'.")
    else:
        if not re.match(r'^[A-Za-z_]+$', name):
            all_failed(label + " name '" + name + "' may contain only characters 'A' - 'Z', 'a' - 'z', and underscore '_'.")

def all_failed(message):
    global ccontent, hcontent
    print(message)
    ccontent += "FAILED: " + message
    hcontent += "FAILED: " + message
    finish_c_files()
    exit()

def start_c_files():
    global ccontent, hcontent, hfilepath
    ccontent = '/* This file is generated by signals_to_c.py script, do not modify. */\n'
    hcontent = '/* This file is generated by signals_to_c.py script, do not modify. */\n'
    path, fname = os.path.split(hfilepath)
    fname, ext = os.path.splitext(fname)
    macroname = 'IOC_' + fname.upper() + '_INCLUDED'
    hcontent += '#ifndef ' + macroname + '\n'
    hcontent += '#define ' + macroname + '\n'
    hcontent += 'OSAL_C_HEADER_BEGINS\n\n'

def finish_c_files():
    global ccontent, hcontent
    hcontent += '\nOSAL_C_HEADER_ENDS\n'
    hcontent += '#endif\n'

def write_signal_to_c_header(signal_name):
    global hcontent
    hcontent += "    iocSignal " + signal_name + ";\n"

def calc_signal_memory_sz(type, array_n):
    if type == "boolean":
        if array_n <= 1:
            return 1
        else:
            return ((array_n + 7) >> 3) + 1

    type_sz = osal_typeinfo[type]
    return array_n * type_sz + 1

